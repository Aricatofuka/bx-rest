/**
 * Событие `.resAllWithProgress()` после очередного HTTP-ответа обхода: первой страницы,
 * каждого запроса `batch` или каждой страницы, если страницы запрашиваются по одной.
 */
export interface BXRestResAllProgress<R> {
  type: 'progress'
  /** Сколько записей получено к этому моменту, вместе с записями этого ответа. */
  loaded: number
  /**
   * Сколько записей отдаст обход: общее число записей из ответа Bitrix. Если запрос начинается
   * не с первой записи (`start`, `OFFSET`, номер страницы), записи до начала не считаются.
   * `undefined`, если метод общего числа не отдаёт: так у методов, которые листаются по одной странице.
   */
  total: number | undefined
  /**
   * Записи этого ответа в той же форме, что результат `.resAll()`, уже обработанные маппером метода.
   * У метода, который отдаёт массив, — массив записей ответа. У метода со списком под ключом —
   * такой же объект с записями ответа под ключом.
   */
  items: R
}

/** Последнее событие `.resAllWithProgress()`. */
export interface BXRestResAllDone<R> {
  type: 'done'
  /** То же, что отдаёт `.resAll()`. */
  result: R
}

/**
 * Событие `.resAllWithProgress()`: `progress` после каждого HTTP-ответа, `done` один раз в конце.
 * `R` — тип результата `.resAll()`.
 */
export type BXRestResAllEvent<R> = BXRestResAllProgress<R> | BXRestResAllDone<R>
